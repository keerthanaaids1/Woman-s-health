"""
AGENT 5: ClinicalBriefComposer
Transforms patient's raw regional narrative, decoded clinical markers, and triage metrics
into an executive, professional 1-page Clinical Consultation Dossier for their Gynecologist.
Empowers the patient so she walks into her doctor's clinic confident, organized, and informed.
"""

from datetime import datetime
from typing import Dict, Any

def compose_doctor_brief(
    patient_profile: Dict[str, Any],
    decoder_data: Dict[str, Any],
    triage_data: Dict[str, Any],
    hygiene_data: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Assembles a clinical summary card and markdown report for medical review.
    """
    patient_name = patient_profile.get("name", "Patient")
    age = patient_profile.get("age", "Not specified")
    cycle_length = patient_profile.get("cycle_length_days", "Irregular / Variable")
    last_period_date = patient_profile.get("last_period_date", "Uncertain")
    
    symptoms = [s.get("clinical_term") for s in decoder_data.get("matched_symptoms", [])]
    
    # Generate formatted markdown brief
    md_report = f"""# CLINICAL INTAKE & CARE NAVIGATION DOSSIER
**Hospital Facility:** Aura Women's Specialty Health Sanctuary  
**Patient Identifier:** {patient_profile.get("patient_id", "AURA-7749")}  
**Date of Triage:** {datetime.utcnow().strftime('%B %d, %Y')}  
**Age:** {age} years | **Cycle Length:** {cycle_length} | **Last Period:** {last_period_date}  

---

### 1. PATIENT-EXPRESSED CONCERNS (LINGUISTIC TRANSLATION)
* **Raw Colloquial Input:** *"{decoder_data.get('raw_input', 'N/A')}"*
* **Standardized Gynecological Tokens Identified:**
{chr(10).join(f"  - **{s.get('clinical_term')}:** {s.get('significance')}" for s in decoder_data.get('matched_symptoms', []))}

---

### 2. ENDOCRINE & OVULATORY PATTERN EVALUATION (NON-DIAGNOSTIC)
* **Triage Index:** {triage_data.get('triage_score', 0)}/100 ({triage_data.get('triage_level', 'Evaluated')})
* **Clinical Urgency:** {triage_data.get('care_urgency', 'Elective')}
* **Key Phenotypic Flags:**
{chr(10).join(f"  - {indicator}" for indicator in triage_data.get('pattern_indicators', []))}

---

### 3. RECOMMENDED CLINICAL INVESTIGATIONS TO DISCUSS
{chr(10).join(f"* [ ] **{lab['test']}:** {lab['purpose']}" for lab in triage_data.get('recommended_labs', []))}

---

### 4. PATIENT'S PREPARED QUESTIONS FOR GYNECOLOGIST
{chr(10).join(f"{i+1}. {q}" for i, q in enumerate(triage_data.get('doctor_questions', [])))}

---

### 5. DERMATOLOGICAL & MENSTRUAL BARRIER HYGIENE
* **Suggested Product Form:** {hygiene_data.get('primary_recommendation', {}).get('name', 'Organic Cotton')}
* **Clinical Rationale:** {hygiene_data.get('switch_reason', 'Support mucosal flora.')}

---
*Notice: Generated by Aura Care Multi-Agent System for patient empowerment. Not an autonomous medical diagnosis.*
"""

    return {
        "agent": "ClinicalBriefComposer",
        "dossier_id": f"AURA-{datetime.utcnow().strftime('%Y%m%d%H%M')}",
        "patient_name": patient_name,
        "created_at": datetime.utcnow().isoformat(),
        "markdown_report": md_report,
        "quick_summary": {
            "symptoms_identified": symptoms,
            "triage_level": triage_data.get("triage_level"),
            "primary_concern": symptoms[0] if symptoms else "Cycle assessment",
            "recommended_next_step": triage_data.get("care_urgency")
        }
    }
